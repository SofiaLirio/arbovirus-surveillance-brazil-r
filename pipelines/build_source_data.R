# sheets: list of list(name, data, description, source)
write_workbook <- function(name, title, sheets) {
  readme <- data.frame(Sheet = vapply(sheets, `[[`, "", 1), Description = vapply(sheets, `[[`, "", 3),
                       `Derived from` = vapply(sheets, `[[`, "", 4), Rows = vapply(sheets, function(s) nrow(s[[2]]), 0L),
                       check.names = FALSE)
  header <- data.frame(Sheet = c(title, "Generated by pipelines/build_source_data.R", "Incidence = cases per 100,000 inhabitants", ""),
                       Description = "", `Derived from` = "", Rows = NA_integer_, check.names = FALSE)
  out <- c(list(README = rbind(header, readme)), setNames(lapply(sheets, `[[`, 2), vapply(sheets, `[[`, "", 1)))
  write_xlsx_sheets(out, file.path(SRC_DIR, sprintf("%s.xlsx", name)))
  cat(sprintf("  saved -> source_data/%s.xlsx (%d sheets)\n", name, length(sheets)))
}

check_equal <- function(desc, a, b, keys, cols, atol = 1e-9) {
  m <- merge(as.data.table(a), as.data.table(b), by = keys, suffixes = c("_new", "_saved"), all = TRUE)
  ok <- nrow(m) == nrow(a) && nrow(m) == nrow(b)
  for (cc in cols) {
    x <- m[[paste0(cc, "_new")]]; y <- m[[paste0(cc, "_saved")]]
    if (is.numeric(x) && is.numeric(y)) {
      same <- (is.na(x) & is.na(y)) | (!is.na(x) & !is.na(y) & abs(x - y) <= atol + 1e-7 * abs(y))
      ok <- ok && all(same)
    } else ok <- ok && identical(as.character(x), as.character(y))
  }
  CHECKS[[length(CHECKS) + 1]] <<- list(desc, isTRUE(ok))
}

