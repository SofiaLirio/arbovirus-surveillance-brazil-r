# Box statistics as drawn by the boxplots (whiskers = 1.5 IQR; quantiles type 7 = numpy linear)
box_summary <- function(df, by, col) {
  df <- as.data.table(df)
  df[, {
    v <- get(col); v <- v[!is.na(v)]
    q <- stats::quantile(v, c(0.25, 0.5, 0.75), type = 7, names = FALSE); iqr <- q[3] - q[1]
    lo <- min(v[v >= q[1] - 1.5 * iqr]); hi <- max(v[v <= q[3] + 1.5 * iqr])
    list(n = length(v), Q1 = q[1], Median = q[2], Q3 = q[3], Whisker_low = lo, Whisker_high = hi,
         n_outliers = sum(v < lo | v > hi), Mean = mean(v), Max = max(v))
  }, by = by][do.call(order_c, lapply(by, function(b) get(b)))]
}

pzfx_tables <- function() {
  out <- list()
  for (virus in names(gp$FILES))
    for (tbl in gp$read_tables(virus)) out[[length(out) + 1]] <- list(virus = virus, title = tbl$title, df = gp$table_to_df(tbl))
  out
}
find_table <- function(tables, virus, prefix) {
  for (t in tables) if (t$virus == virus && startsWith(t$title, prefix)) return(t)
  stop(sprintf("table not found: %s / %s", virus, prefix))
}

# Counts + the percentages drawn by plot_proportion (graphpad_pipeline.R). Ignored/blank
# categories are flagged and, as in the figures, left out of the denominator (Percent = NA).
categorical_long <- function(df, virus, title) {
  cats <- setdiff(names(df), "Year")
  miss <- cats %in% gp$MISSING_CATS
  m <- as.matrix(df[cats]); totals <- rowSums(m[, !miss, drop = FALSE], na.rm = TRUE); totals[totals == 0] <- NA
  pct <- m / totals * 100; pct[is.na(pct)] <- 0; pct[, miss] <- NA
  data.table(Virus = virus, Table = title, Year = rep(df$Year, length(cats)), Category = rep(cats, each = nrow(df)),
             Count = as.vector(m), Excluded_missing = rep(miss, each = nrow(df)), Percent = as.vector(pct))
}
PCT_NOTE <- "Percent = share of records with a known value; Excluded_missing rows (ignored/blank) are not plotted"

read_adv <- function(name) {
  d <- fread(file.path(OUT_ADV, name), na.strings = "")
  for (cc in names(d)) if (inherits(d[[cc]], c("IDate", "Date"))) set(d, j = cc, value = format(d[[cc]], "%Y-%m-%d"))
  d
}
